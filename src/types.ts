import type { Feature, FeatureCollection, Polygon, Point, Position } from "geojson";
import type {
  IndexedTins,
  Tins,
  VerticesParams,
  WeightBuffer
} from "./geometry.ts";
import type { EdgeSet, EdgeSetLegacy } from "./edgeutils.ts";

/**
 * Two-way coordinate pair: [source, target].
 */
export type PointSet = [Position, Position];

/**
 * Directional selector shared across the codebase.
 */
export type BiDirectionKey = "forw" | "bakw";

/**
 * Weight buffers indexed by node id for both directions.
 *
 * @deprecated 2.00704 以降の MaplatTransform は重みを使わない（型の互換のためだけに残す）
 */
export type WeightBufferBD = { [key in BiDirectionKey]?: WeightBuffer };

/**
 * Vertex interpolation modes.
 */
export type VertexMode = "plain" | "birdeye";

/**
 * Strictness flags supported during transformation.
 */
export type StrictMode = "strict" | "auto" | "loose";

/**
 * Result of strictness evaluation.
 */
export type StrictStatus = "strict" | "strict_error" | "loose";

/**
 * Y-axis handling directive.
 */
export type YaxisMode = "follow" | "invert";

export type Centroid = Feature<Point>;
export type CentroidBD = { [key in BiDirectionKey]?: Centroid };
export type TinsBD = { [key in BiDirectionKey]?: Tins };
export type Kinks = FeatureCollection<Point>;
export type KinksBD = { [key in BiDirectionKey]?: Kinks };
export type VerticesParamsBD = { [key in BiDirectionKey]?: VerticesParams };
export type IndexedTinsBD = { [key in BiDirectionKey]?: IndexedTins };

/**
 * Serialized structure generated by MaplatTin and consumed by Transform.
 */
export interface Compiled {
  version?: number;
  points: PointSet[];
  tins_points: (number | string)[][][];
  /** 書き出し側（MaplatTin 2.00704 以降）は常に `{}` を書く。以前の MaplatTransform はこのキーが無いと `transform()` で TypeError になるため、省略してはならない。読み込み側は値を無視する */
  weight_buffer: WeightBufferBD;
  strict_status?: StrictStatus;
  centroid_point: Position[];
  edgeNodes?: PointSet[];
  kinks_points?: Position[];
  yaxisMode?: YaxisMode;
  vertexMode?: VertexMode;
  strictMode?: StrictMode;
  vertices_params: number[][];
  vertices_points: PointSet[];
  edges?: EdgeSet[];
  bounds?: number[][];
  boundsPolygon?: Feature<Polygon>;
  wh?: number[];
  xy?: number[];
}

/** 外側を world file で補う三角網。既存の Compiled の公開型は変更しない */
export interface CompiledWorldFileOuter extends Omit<Compiled, "centroid_point" | "vertices_params"> {
  outerTransform: "worldFile";
  worldFile: WorldFile;
  vertices_points: PointSet[];
  centroid_point?: Position[];
  vertices_params?: number[][];
}

export type CompiledExtrapolate = Compiled & { outerTransform: "extrapolate"; worldFile?: never };
export type CompiledTransformData = Compiled | CompiledWorldFileOuter | CompiledExtrapolate;

/** 業界標準の world file 係数。原点は左上画素の中心 */
export interface WorldFile {
  xScale: number;
  xSkew: number;
  xOrigin: number;
  ySkew: number;
  yScale: number;
  yOrigin: number;
}

/** CRS の識別子と変換定義 */
export interface CrsObject {
  epsg?: number;
  proj4?: string;
  authority?: string;
  code?: string | number;
  wkt?: string;
}

/** CRS と経緯度の変換を行う拡張可能な投影エンジン */
export interface ProjectionEngine {
  toLonLat(coord: number[], crs: CrsObject): number[] | false;
  fromLonLat(lonLat: number[], crs: CrsObject): number[] | false;
  /** 定義を読み込み、内蔵 CRS との照合が必要なときは CRS 座標の標本点を検査する */
  validateDefinition?(crs: CrsObject, samplePoints?: number[][]): void;
}

/** MapTransform が扱う変換面の共通口 */
export interface SurfaceLike {
  transform(coord: number[], backward?: boolean, ignoreBounds?: boolean): number[] | false;
  wh?: number[];
  xy?: number[];
  bounds?: number[][];
  priority?: number;
  importance?: number;
}

export interface TinSurfaceData {
  kind: "tin";
  compiled: CompiledTransformData;
  crs?: CrsObject;
  projectionEngine?: ProjectionEngine;
  priority?: number;
  importance?: number;
  bounds?: number[][];
}

type WorldFileSurfaceDimensions = { wh: number[]; bounds?: number[][] } | { wh?: undefined; bounds: [number[], number[], number[], ...number[][]] };

export type WorldFileSurfaceData = WorldFileSurfaceDimensions & {
  kind: "worldFile";
  crs: CrsObject;
  worldFile: WorldFile;
  wh?: number[];
  xy?: number[];
  bounds?: number[][];
  priority?: number;
  importance?: number;
  projectionEngine?: ProjectionEngine;
};

export type LayerSurfaceData = TinSurfaceData | WorldFileSurfaceData;

/**
 * 視点変換モード（地図全体＝本図＋全副層で共通の 1 組、設計書 §3.2）。
 * 未指定（省略）は "grid"（モード 2）として動作する。
 */
export type ViewpointMode = "constant" | "grid";

export interface LayeredMapData {
  main: LayerSurfaceData;
  sub_maps?: LayerSurfaceData[];
  maxZoom?: number;
  viewpointMode?: ViewpointMode;
}

/**
 * Historical serialization format prior to 2.00703.
 */
export interface CompiledLegacy extends Compiled {
  tins?: TinsBD;
  centroid?: CentroidBD;
  kinks?: KinksBD;
  vertices_params: number[][] & VerticesParamsBD;
  edges: EdgeSet[] & EdgeSetLegacy[];
}

/**
 * Normalized state derived from modern compiled payloads.
 */
export interface ModernStatePayload {
  points: PointSet[];
  strictStatus: StrictStatus;
  verticesParams: VerticesParamsBD;
  centroid: CentroidBD;
  edges: EdgeSet[];
  edgeNodes?: PointSet[];
  tins: TinsBD;
  kinks?: KinksBD;
  yaxisMode: YaxisMode;
  strictMode: StrictMode;
  vertexMode?: VertexMode;
  bounds?: number[][];
  boundsPolygon?: Feature<Polygon>;
  wh?: number[];
  xy?: number[];
}

/**
 * Normalized snapshot captured from legacy payloads.
 */
export interface LegacyStatePayload {
  compiled: CompiledLegacy;
  tins: TinsBD;
  points: PointSet[];
  strictStatus?: StrictStatus;
  verticesParams: VerticesParamsBD;
  centroid?: CentroidBD;
  kinks?: KinksBD;
}

// ─── MapTransform types ───────────────────────────────────────────────────────

/**
 * Viewport representation: center in mercator, zoom level, rotation in radians.
 */
export interface Viewpoint {
  /** Mercator coordinate [x, y] */
  center: number[];
  /** Mercator zoom level */
  zoom: number;
  /** Rotation angle in radians */
  rotation: number;
}

/**
 * Sub-map TIN data for MapTransform.setMapData().
 */
export interface SubMapData {
  /** Compiled TIN data */
  compiled: Compiled;
  /** Layer priority (higher = checked first) */
  priority: number;
  /** Layer importance (used when multiple layers overlap) */
  importance: number;
  /** Bounds vertices in pixel (XY) space. Falls back to compiled.bounds if omitted. */
  bounds?: number[][];
}

/**
 * Input data for MapTransform.setMapData().
 */
export interface MapData {
  /** Compiled TIN data for the main layer */
  compiled: Compiled;
  /** maxZoom value used to compute _maxxy = 2^maxZoom * 256 */
  maxZoom?: number;
  /** Sub-map layers */
  sub_maps?: SubMapData[];
  /** 視点変換モード（地図全体で共通。省略時は "grid"） */
  viewpointMode?: ViewpointMode;
}

/** 視点係数（局所相似）。s は [EPSG:3857 単位 / 地図画素]、theta は地図の局所回転角（ラジアン） */
export interface ViewpointCoefficients {
  s: number;
  theta: number;
}

/** recommendViewpointMode の結果（設計書 §5.3 1.） */
export interface RecommendViewpointModeResult {
  /** 推奨モード（判定統計が閾値内なら "constant"、超過なら "grid"） */
  recommended: ViewpointMode;
  /** G_in 内の最大回転偏差（度） */
  maxRotationDiffDeg: number;
  /** G_in 内の回転偏差 95% 分位値（度） */
  p95RotationDiffDeg: number;
  /** G_in 内の最大相対縮尺偏差（比率） */
  maxScaleRatioDiff: number;
  /** G_in 内の相対縮尺偏差 95% 分位値（比率） */
  p95ScaleRatioDiff: number;
  /** 判定に使った標本点数（|G_in|） */
  sampleCount: number;
}

/** recommendViewpointMode の省略可能引数 */
export interface RecommendViewpointModeOptions {
  /** 層の投影エンジン（既定は内蔵エンジン） */
  projectionEngine?: ProjectionEngine;
  /** 紙座標を含む GCP 列（各要素の先頭 gcp[0] を紙座標として参照。TIN 層の compiled.points より優先） */
  gcps?: PointSet[];
}
